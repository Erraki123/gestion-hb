// HN BLOOM - repeated branded Chromium PDF header/footer
// Keeps V26 ReturnAsBase64 to avoid Windows CDP IO.read stream failures.
// V29_MULTI_PAGE_PRINT
'use strict';
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');
const puppeteer = require('puppeteer-core');

const [input, output] = process.argv.slice(2);
if (!input || !output || !fs.existsSync(input)) {
  console.error('Usage: node render.cjs input.html output.pdf');
  process.exit(2);
}
const candidates = [
  process.env.HNB_CHROME_PATH,
  'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',
  'C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe',
  'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
  'C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe',
  '/usr/bin/chromium', '/usr/bin/google-chrome'
].filter(Boolean);
const executablePath = candidates.find(candidate => fs.existsSync(candidate));
if (!executablePath) {
  console.error('Chrome/Edge not found; set HNB_CHROME_PATH.');
  process.exit(3);
}

(async () => {
  let browser, page, session;
  try {
    // HNB_PDF_CHROME_HOSTINGER_V2: keep local Windows launch unchanged.
    // Hostinger CLI uses low-process pipe mode; web requests never launch Chrome.
    const limitedLinux = process.platform === 'linux';
    browser = await puppeteer.launch({
      executablePath, headless: true,
      ...(limitedLinux ? {pipe: true, dumpio: true, timeout: 15000} : {}),
      args: limitedLinux ? [
        '--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu',
        '--disable-extensions', '--disable-background-networking',
        '--disable-breakpad', '--disable-features=MediaRouter',
        '--no-first-run', '--no-zygote', '--single-process',
        '--renderer-process-limit=1'
      ] : ['--no-sandbox', '--disable-dev-shm-usage']
    });

    page = await browser.newPage();
    await page.goto(pathToFileURL(path.resolve(input)).href, {
      waitUntil: 'load', timeout: 30000
    });
    await page.evaluate(async () => { await document.fonts.ready; });

    // Take the existing branded header/footer from the HTML generated by
    // Laravel. The source, logos, icons, and company fields stay unchanged.
    const layout = await page.evaluate(() => ({
      css: Array.from(document.querySelectorAll('style'))
        .map(node => node.textContent).join('\n'),
      header: document.querySelector('header.masthead')?.outerHTML || '',
      footer: document.querySelector('footer.page-footer')?.outerHTML || ''
    }));
    if (!layout.header || !layout.footer) {
      throw new Error('Missing .masthead or .page-footer; source template unsupported.');
    }
    // HNB_V31_REMOVE_ORIGINAL_PRINT_FURNITURE
    // Keep the copied branded header/footer only in Chromium print templates.
    await page.evaluate(() => {
      document.querySelectorAll('header.masthead, footer.page-footer').forEach(el => el.remove());
    });

    // HNB_V33_ISOLATED_PRINT_FURNITURE
    // V33: Print templates have an independent Chromium document.
    // NEVER inject full Laravel CSS here: @media screen/@media print,
    // @page and .page-footer fixed positioning can move footer to the TOP.
    // Keep print furniture styles isolated and deterministic.
    const furnitureCss = `<style>
      * { box-sizing:border-box; }
      html, body { margin:0; padding:0; background:transparent; color:#1c2930;
        font-family:Arial,Helvetica,sans-serif; font-size:10pt; }
      .masthead { width:100%; margin:0; border-bottom:1.5px solid #b28a50;
        padding-bottom:6px; }
      .brand-row { display:flex; align-items:center; justify-content:space-between;
        gap:14px; }
      .brand-col { width:39%; min-width:0; }
      .brand-logo { max-width:66mm; max-height:28mm; object-fit:contain;
        object-position:left center; }
      .brand-word { font-family:Georgia,serif; font-size:27pt; color:#b28a50;
        line-height:1; }
      .brand-word span {font-size:14pt; display:block;}
      .brand-tag { margin-top:4px; font-family:Georgia,serif; font-size:6.9pt;
        letter-spacing:1.15px; color:#766853; white-space:nowrap; }
      .brand-tag b {color:#b28a50;}
      .service-band {display:flex;align-items:stretch;justify-content:space-between;
        width:60%;min-height:24mm;border:1px solid #d0ae77;
        border-right:3px solid #b28a50;
        background:linear-gradient(115deg,#fffaf1,#f3e9d7 60%,#f9f2e7);
        clip-path:polygon(5% 0,100% 0,100% 100%,0 100%);}
      .service-icon {flex:1;display:flex;flex-direction:column;align-items:center;
        justify-content:center;gap:3px;text-align:center;border-left:1px solid #d4ba91;
        min-width:0;}
      .service-icon:first-child {border-left:0;}
      .service-icon svg {width:26px;height:26px;fill:none;stroke:#97713c;
        stroke-width:1.8;stroke-linecap:round;stroke-linejoin:round;}
      .service-icon span {font-size:6.4pt;font-weight:700;letter-spacing:.4px;
        color:#775b34;}
      .services-description {font-size:9pt;margin-top:6px;color:#545052;
        letter-spacing:.25px;}
      .services-description i {font-style:normal;color:#b28a50;padding:0 4px;}
      .page-footer {display:block;position:static;bottom:auto;left:auto;
        right:auto;width:100%;margin:0;padding:0;color:#273a43;
        font-size:7.5pt;min-height:0;background:transparent;}
      .footer-top {height:1.5px;background:#b48b50;margin-bottom:7px;}
      .footer-flex {display:flex;justify-content:space-between;
        align-items:flex-start;gap:8px;}
      .footer-block {display:flex;gap:5px;align-items:flex-start;min-width:0;
        max-width:22%;overflow-wrap:anywhere;}
      .footer-block.address {max-width:40%;flex:1.5;}
      .footer-block div {min-width:0;}
      .footer-block strong {display:block;font-size:8pt;color:#926f3f;
        margin-bottom:2px;}
      .footer-block span:not(.footer-ico) {display:block;line-height:1.35;}
      .footer-ico {font-size:13pt;color:#b28a50;line-height:1;}
      .footer-sweep {display:none;}
      .page-number {text-align:right;font:7pt Arial,Helvetica,sans-serif;
        margin-top:1mm;color:#82735c;}
    </style>`;
    const wrapper = content => `<div style="width:100%;box-sizing:border-box;
      padding:0 13mm;font-family:Arial,Helvetica,sans-serif;
      -webkit-print-color-adjust:exact;print-color-adjust:exact;">
      ${furnitureCss}${content}</div>`;
    const headerTemplate = wrapper(layout.header);
    const footerTemplate = wrapper(`${layout.footer}
      <div class="page-number">Page <span class="pageNumber"></span> /
        <span class="totalPages"></span></div>`);

    // Reserve real print margins for the repeated header and footer.
    // IMPORTANT: do not use @page margin:0; it makes tables overlap header.
    await page.addStyleTag({content: `
      @page { size:A4 portrait; margin:55mm 13mm 27mm !important; }
      .sheet > .masthead, body > .page-footer { display:none!important; }
      .sheet { max-width:none!important; }
      .line-table thead, .payment-table thead {
        display:table-header-group!important;
      }
      .line-table tr, .payment-table tr {
        break-inside:avoid!important; page-break-inside:avoid!important;
      }
      .summary-row, .signature-row {
        break-inside:avoid!important; page-break-inside:avoid!important;
      }
    `});
    await page.emulateMediaType('print');
    session = await page.createCDPSession();

    // Keep PDF transport as base64: avoids the IO.read errors observed when
    // Edge is launched from Laravel/PHP on Windows.
    const result = await session.send('Page.printToPDF', {
      landscape: false,
      printBackground: true,
      preferCSSPageSize: false,
      paperWidth: 8.2677165,
      paperHeight: 11.6929134,
      marginTop: 55 / 25.4,
      marginRight: 13 / 25.4,
      marginBottom: 27 / 25.4,
      marginLeft: 13 / 25.4,
      displayHeaderFooter: true,
      headerTemplate,
      footerTemplate,
      transferMode: 'ReturnAsBase64'
    });
    if (!result || !result.data) throw new Error('Chromium returned empty PDF data');
    const pdfBytes = Buffer.from(result.data, 'base64');
    if (pdfBytes.length < 500 || pdfBytes.subarray(0, 5).toString() !== '%PDF-') {
      throw new Error('Invalid PDF received from Chromium');
    }
    const target = path.resolve(output);
    fs.mkdirSync(path.dirname(target), {recursive:true});
    fs.writeFileSync(target, pdfBytes);
    console.log('PDF_OK', target);
  } finally {
    if (session) await session.detach().catch(() => {});
    if (page) await page.close().catch(() => {});
    if (browser) await browser.close().catch(() => {});
  }
})().catch(error => {
  console.error('HNB_CHROME_RENDER_ERROR:', error.stack || String(error));
  process.exitCode = 1;
});
