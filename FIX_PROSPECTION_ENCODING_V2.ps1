$count = 0
foreach($rel in $files) {
 if (-not (Test-Path -LiteralPath $rel)) { Write-Host "Skip (not found): $rel"; continue }
 $full = (Resolve-Path -LiteralPath $rel).Path
 $original = [System.IO.File]::ReadAllText($full, $utf8Strict)
 $updated = $original
 # Repeated passes also correct text double-encoded in older patches.
 for($pass=0; $pass -lt 2; $pass++) {
   foreach($pair in $pairs) {
      $bad = From-Codes ([string]::Join(',', [string[]]$pair[0]')
      $good = From-Codes ([string]::Join(',', [string[]]$pair[1]')
      $updated = $updated.Replace($bad, $good)
   }
 }
 if($updated -cne $original) {
    $destination = Join-Path $backup $rel
    New-Item -ItemType Directory -Path (Split-Path $destination) -Force | Out-Null
    Copy-Item -LiteralPath $full -Destination $destination -Force
    [System.IO.File]::WriteAllText($full, $updated, $utf8Write)
    $count++
    Write-Host "Fixed: $rel" -ForegroundColor Green
 } else { Write-Host "Already clean or no known corrupt sequences: $rel" }
}
