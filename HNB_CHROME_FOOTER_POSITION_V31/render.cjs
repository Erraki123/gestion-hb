// HN BLOOM - repeated branded Chromium PDF header/footer
// Keeps V26 ReturnAsBase64 to avoid Windows CDP IO.read stream failures.
// V29_MULTI_PAGE_PRINT
'use strict';
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');
const puppeteer = require('puppeteer-core');

const [input, output] = process.argv.slice(2);
if (!input || !output || !fs.existsSync(input)) {
  console.error('Usage: node render.cjs input.html output.pdf');
  process.exit(2);
}
const candidates = [
  process.env.HNB_CHROME_PATH,
  'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',
  'C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe',
  'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
  'C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe',
  '/usr/bin/chromium', '/usr/bin/google-chrome'
].filter(Boolean);
const executablePath = candidates.find(candidate => fs.existsSync(candidate));
if (!executablePath) {
  console.error('Chrome/Edge not found; set HNB_CHROME_PATH.');
  process.exit(3);
}

(async () => {
  let browser, page, session;
  try {
    browser = await puppeteer.launch({
      executablePath, headless: true,
      args: ['--no-sandbox', '--disable-dev-shm-usage']
    });
    page = await browser.newPage();
    await page.goto(pathToFileURL(path.resolve(input)).href, {
      waitUntil: 'load', timeout: 30000
    });
    await page.evaluate(async () => { await document.fonts.ready; });

    // Take the existing branded header/footer from the HTML generated by
    // Laravel. The source, logos, icons, and company fields stay unchanged.
    const layout = await page.evaluate(() => ({
      css: Array.from(document.querySelectorAll('style'))
        .map(node => node.textContent).join('\n'),
      header: document.querySelector('header.masthead')?.outerHTML || '',
      footer: document.querySelector('footer.page-footer')?.outerHTML || ''
    }));
    if (!layout.header || !layout.footer) {
      throw new Error('Missing .masthead or .page-footer; source template unsupported.');
    }
    // HNB_V31_REMOVE_ORIGINAL_PRINT_FURNITURE
    // Important: move page furniture into Chromium's page templates only.
    // CSS hiding alone isn't reliable when older print CSS overrides position.
    await page.evaluate(() => {
      document.querySelectorAll('header.masthead, footer.page-footer').forEach(el => el.remove());
    });

    // Chromium page header/footer templates are rendered in an independent
    // print context. Provide their actual CSS and existing markup explicitly.
    const commonCss = `<style>${layout.css}\n
      html,body {margin:0!important; padding:0!important;
        background:transparent!important; color:#25221e!important;}
      * {box-sizing:border-box!important;}
      .masthead {margin:0!important; padding-bottom:8px!important;}
      .page-footer {position:static!important; bottom:auto!important;
        margin:0!important; padding:2px 0 0!important;
        width:100%!important; min-height:0!important;}
      .footer-sweep {display:none!important;}
      .footer-flex {font-size:7.3pt!important;}
    </style>`;
    const wrapper = content => `<div style="width:100%; box-sizing:border-box;
      padding:0 13mm; font-family:Arial,Helvetica,sans-serif;
      -webkit-print-color-adjust:exact; print-color-adjust:exact;">
      ${commonCss}${content}</div>`;
    const headerTemplate = wrapper(layout.header);
    const footerTemplate = wrapper(`${layout.footer}
      <div style="text-align:right;font:7pt Arial,Helvetica,sans-serif;
        margin-top:1mm;color:#82735c;">
        Page <span class="pageNumber"></span> / <span class="totalPages"></span>
      </div>`);

    // Reserve real print margins for the repeated header and footer.
    // IMPORTANT: do not use @page margin:0; it makes tables overlap header.
    await page.addStyleTag({content: `
      @page { size:A4 portrait; margin:55mm 13mm 27mm !important; }
      .sheet > .masthead, body > .page-footer { display:none!important; }
      .sheet { max-width:none!important; }
      .line-table thead, .payment-table thead {
        display:table-header-group!important;
      }
      .line-table tr, .payment-table tr {
        break-inside:avoid!important; page-break-inside:avoid!important;
      }
      .summary-row, .signature-row {
        break-inside:avoid!important; page-break-inside:avoid!important;
      }
    `});
    await page.emulateMediaType('print');
    session = await page.createCDPSession();

    // Keep PDF transport as base64: avoids the IO.read errors observed when
    // Edge is launched from Laravel/PHP on Windows.
    const result = await session.send('Page.printToPDF', {
      landscape: false,
      printBackground: true,
      preferCSSPageSize: false,
      paperWidth: 8.2677165,
      paperHeight: 11.6929134,
      marginTop: 55 / 25.4,
      marginRight: 13 / 25.4,
      marginBottom: 27 / 25.4,
      marginLeft: 13 / 25.4,
      displayHeaderFooter: true,
      headerTemplate,
      footerTemplate,
      transferMode: 'ReturnAsBase64'
    });
    if (!result || !result.data) throw new Error('Chromium returned empty PDF data');
    const pdfBytes = Buffer.from(result.data, 'base64');
    if (pdfBytes.length < 500 || pdfBytes.subarray(0, 5).toString() !== '%PDF-') {
      throw new Error('Invalid PDF received from Chromium');
    }
    const target = path.resolve(output);
    fs.mkdirSync(path.dirname(target), {recursive:true});
    fs.writeFileSync(target, pdfBytes);
    console.log('PDF_OK', target);
  } finally {
    if (session) await session.detach().catch(() => {});
    if (page) await page.close().catch(() => {});
    if (browser) await browser.close().catch(() => {});
  }
})().catch(error => {
  console.error('HNB_CHROME_RENDER_ERROR:', error.stack || String(error));
  process.exitCode = 1;
});
